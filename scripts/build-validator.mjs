#!/usr/bin/env node
// Compile schema/messages.schema.json into a standalone validator the Pages
// Function can import: functions/api/_messages-validator.mjs.
//
// WHY A BUILD STEP. `PUT /api/messages` has to validate server-side, and the
// Workers runtime forbids `new Function` and `eval`, which is exactly how Ajv
// turns a schema into a validator at runtime. So the compilation happens here,
// ahead of time, and the Function imports the generated code.
//
// The alternative was hand-writing the rules a second time inside the Function.
// That is the trap the `a-fact-stored-twice-is-checked-once` learning names: two
// copies of one fact, only one of which anyone remembers to update. The schema
// stays the single source of truth, and CI regenerates this file and fails on a
// diff, so drift cannot land quietly.
//
// Run: npm run build:validator

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve, relative } from "node:path";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const schemaPath = join(root, "schema", "messages.schema.json");
const outPath = join(root, "functions", "api", "_messages-validator.mjs");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

// No ajv-formats. The generated module has to stand alone in the Workers bundle,
// and a format keyword compiles to a reference back into the ajv-formats package.
// `date` is a `pattern` in the schema instead; see the note there.
const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: true });
const validate = ajv.compile(schema);

let code = standaloneCode(ajv, validate);

// Ajv emits `require("ajv/dist/runtime/ucs2length")` for minLength/maxLength,
// because JS `.length` counts UTF-16 code units and a schema means code points.
// A bare `require` in an ESM module is not portable into the Workers bundle, and
// pulling all of ajv in for a five-line helper is worse. Inline it instead.
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length;
  let length = 0, pos = 0, value;
  while (pos < len) {
    length++;
    value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}
`;
code = code.replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/,
  (_m, name) => `${UCS2LENGTH}const ${name} = ucs2length;`,
);

// Any OTHER runtime import means a schema keyword was added that this script has
// not been taught to inline. Fail loudly: a `require` that reaches the Workers
// bundle fails at request time, on the write path, in production.
if (/require\(/.test(code)) {
  const offending = code.match(/require\([^)]*\)/g) ?? [];
  console.error(
    `FAIL  generated validator still calls require(): ${offending.join(", ")}\n` +
      "      A new schema keyword needs its ajv runtime helper inlined here.",
  );
  process.exit(1);
}

const banner = `// GENERATED by scripts/build-validator.mjs from schema/messages.schema.json.
// Do not edit. Run \`npm run build:validator\`; CI fails on a diff.
`;

writeFileSync(outPath, banner + code);
console.log(`ok  wrote ${relative(root, outPath)}`);

// The types for it, emitted alongside so the two cannot ship apart. This shape
// comes from Ajv's standalone contract, not from our schema, so it does not
// change when the schema does.
const dtsPath = outPath.replace(/\.mjs$/, ".d.mts");
writeFileSync(
  dtsPath,
  `${banner}
/** One Ajv error. \`message\` is optional in Ajv's own types, so it is here too. */
export interface ValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}

export interface ValidateFunction {
  (data: unknown): boolean;
  /** Populated on a failed call, reset on the next one. */
  errors?: ValidationError[] | null;
}

declare const validate: ValidateFunction;
export default validate;
export { validate };
`,
);
console.log(`ok  wrote ${relative(root, dtsPath)}`);
